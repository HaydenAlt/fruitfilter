export const STRINGS: Record<Lang, Record<StringKey, string>> = { en, 'zh-HK': zhHK }

export function t(lang: Lang, key: StringKey, vars?: Record<string, string | number>): string {
  let value = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement))
    }
  }
  return value
}

export const LangContext = createContext<Lang>('en')

export function useLang(): Lang {
  return useContext(LangContext)
}

export function useT() {
  const lang = useLang()
  return useCallback(
    (key: StringKey, vars?: Record<string, string | number>) => t(lang, key, vars),
    [lang],
  )
}

export function applyLang(lang: Lang): void {
  document.documentElement.lang = lang === 'zh-HK' ? 'zh-HK' : 'en'
}

export function useLangSideEffects(lang: Lang): void {
  useEffect(() => {
    applyLang(lang)
  }, [lang])
}
